const dicts = { el, en };

export function t(key, params) {
  const d = dicts[lang.value] || el;
  let s = d[key];
  if (s === undefined) s = el[key] ?? en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
  return s;
}

/** Localised piece name (for accessibility / aria labels). */
export function roleName(role) {
  const names = {
    el: { pawn: 'πιόνι', knight: 'ίππος', bishop: 'αξιωματικός', rook: 'πύργος', queen: 'βασίλισσα', king: 'βασιλιάς' },
    en: { pawn: 'pawn', knight: 'knight', bishop: 'bishop', rook: 'rook', queen: 'queen', king: 'king' },
  };
  return (names[lang.value] || names.el)[role] || role;
}

